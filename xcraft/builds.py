"""The lock of the builds: ``xcraft.builds``, the build ID of each package of ours, and what its builds found that its
spec does not say, which the resolution of the build roots needs before building, see docs/lock-design.md.

One file, by package, for plain line-based merges: each line starts with the name of its package, after a comment line
with it, and the lines of a package end with a blank line, so that the changes of different packages are never next to
each other.
"""

from __future__ import annotations

import json
import re
import tomllib
from typing import TYPE_CHECKING

from pydantic import BaseModel, ConfigDict, Field

from xcraft.display import changes
from xcraft.lock import Recorded
from xcraft.project import write_atomically

if TYPE_CHECKING:
    from pathlib import Path

    from xcraft.packages import Binary, Package
    from xcraft.project import Project

FIELDS = ("buildrequires", "requires", "provides")
"""What the builds record: by package, its dynamic BuildRequires; by binary package, the packages the requirements rpm
generated for it resolve to, and the capabilities rpm generated for it that a spec of ours requires."""
_HEADER = "# written by xcraft: the builds of our packages, and what they found that the specs do not say\n"


class BuildId(BaseModel):
    """The build ID of a package."""

    number: int = Field(ge=1)
    key: str = Field(pattern=r"^[0-9a-f]{64}$")
    """The build key, the same on all the architectures."""
    accepts: str | None = Field(default=None, pattern=r"^[0-9a-f]{64}$")
    """The build key a reused build is accepted for, the current one: an equivalence, chosen with xcraft reuse."""

    def text(self) -> str:
        """Return it on one line: ``<number> <key>``, and ``accepts <key>`` for a reused build."""
        return f"{self.number} {self.key}" + (f" accepts {self.accepts}" if self.accepts else "")

    def matches(self, key: str) -> bool:
        """Return whether a package of build `key` has this build ID: built from it, or reusing it for it."""
        return key in (self.key, self.accepts)

    def same(self, other: BuildId | None) -> bool:
        """Return whether `other` is the same build: of the same number and key."""
        return other is not None and (self.number, self.key) == (other.number, other.key)


class Builds(BaseModel):
    """The content of the lock of the builds."""

    model_config = ConfigDict(extra="forbid")

    ids: dict[str, BuildId] = {}
    buildrequires: Recorded = Recorded()
    """For each package of ours with dynamic BuildRequires, those requirements."""
    requires: Recorded = Recorded()
    """For each binary package of ours, the packages its requirements generated by rpm resolve to."""
    provides: Recorded = Recorded()
    """For each binary package of ours, the capabilities generated by rpm that a spec of ours requires, but those its
    spec declares, with its EVR, or its version, as %{evr}, or %{version}."""


def builds_path(project: Project) -> Path:
    """Return the lock of the builds of the project."""
    return project.root / "xcraft.builds"


def _package(line: str) -> str:
    """Return the package of a line of the file, or of its comment line."""
    if line.startswith("# "):
        return line[2:]
    return json.loads(line[: line.index('"', 1) + 1]) if line.startswith('"') else line.split(".", 1)[0]


def _unconflicted(text: str) -> str:
    """Return `text` without its conflicts, git's or jj's, and the lines of their packages."""
    kept, conflicted, inside = [], set(), False
    for line in text.splitlines():
        if line.startswith("<<<<<<<"):
            inside = True
        elif line.startswith(">>>>>>>"):
            inside = False
        elif not inside:
            kept.append(line)
        elif (line := line.lstrip("+- ")) and not re.match(r"([=|%+\\-])\1{6}", line):
            conflicted.add(_package(line))
    return "\n".join(line for line in kept if not line or _package(line) not in conflicted)


def parse_builds(text: str) -> Builds:
    """Return the lock of the builds of the content of its file, without the packages of its merge conflicts: update()
    of xcraft.buildid gives their build IDs again, and their builds what they record.
    """
    builds = Builds()
    for package, entries in tomllib.loads(_unconflicted(text)).items():
        if "build" in entries:
            builds.ids[package] = BuildId(number=entries["build"], key=entries["key"], accepts=entries.get("accepts"))
        for arch, found in [
            ("", entries),
            *((a, v) for a, v in entries.items() if isinstance(v, dict) and a not in FIELDS),
        ]:
            for field in FIELDS:
                if field in found:
                    recorded = getattr(builds, field)
                    into = recorded.arches.setdefault(arch, {}) if arch else recorded.shared
                    into.update({package: found[field]} if field == "buildrequires" else found[field])
    return builds


def load_builds(project: Project) -> Builds:
    """Return the lock of the builds of the project, empty when there is none yet."""
    path = builds_path(project)
    return parse_builds(path.read_text()) if path.exists() else Builds()


def _parsed(project: Project) -> dict[str, dict[str, Package]]:
    """Return the packages of the project as parsed for each architecture, with those it parsed already."""
    return {p.arch: (project if p.platform == project.platform else p).parsed for p in project.all_platforms()}


def toml_key(name: str) -> str:
    """Return `name` as a key of TOML: bare, or quoted."""
    return name if re.fullmatch(r"[A-Za-z0-9_-]+", name) else json.dumps(name)


def render(project: Project, builds: Builds) -> str:
    """Return the content of the file of `builds`, with the records of the binary packages and packages the specs of
    the project have only.
    """
    # the specs parsed only for records of binary packages
    records = any(r.shared or r.arches for r in (builds.requires, builds.provides))
    owners = {
        b.name: name
        for parsed in (_parsed(project) if records else {}).values()
        for name, p in parsed.items()
        for b in p.binaries
    }
    lines: dict[str, list[str]] = {}

    def add(package: str, key: str, value: object) -> None:
        lines.setdefault(package, []).append(f"{toml_key(package)}.{key} = {json.dumps(value)}")

    for name, i in builds.ids.items():
        add(name, "build", i.number)
        add(name, "key", i.key)
        if i.accepts:
            add(name, "accepts", i.accepts)
    arches = sorted({a for field in FIELDS for a in getattr(builds, field).arches})
    for arch in ["", *arches]:
        for field in FIELDS:
            recorded = getattr(builds, field)
            for name, values in sorted((recorded.arches.get(arch, {}) if arch else recorded.shared).items()):
                key = f"{arch}.{field}" if arch else field
                if field == "buildrequires" and name in project.package_dirs:
                    add(name, key, values)
                elif field != "buildrequires" and name in owners:
                    add(owners[name], f"{key}.{json.dumps(name)}", values)
    return _HEADER + "".join(
        f"\n# {package}\n" + "".join(f"{line}\n" for line in lines[package]) for package in sorted(lines)
    )


def save_builds(project: Project, builds: Builds) -> None:
    """Write the lock of the builds of the project, when it changes. When the project is `frozen`, fail instead."""
    path = builds_path(project)
    current = path.read_text() if path.exists() else ""
    if (text := render(project, builds)) == (current or _HEADER):
        return
    if project.frozen:
        differences = changes(*({line for line in t.splitlines() if line and line[0] != "#"} for t in (current, text)))
        msg = f"the lock of the builds would change, which --locked forbids: {', '.join(differences)}"
        raise RuntimeError(msg)
    write_atomically(path, text)


def drop_gone(project: Project) -> None:
    """Drop from the lock of the builds what the builds of packages and binary packages gone recorded, holding the lock
    of the project only then, for the commands only reading the project, like xcraft status during a build.
    """
    path = builds_path(project)
    current = path.read_text() if path.exists() else ""
    if render(project, parse_builds(current)) != (current or _HEADER):
        with project.lock():
            save_builds(project, load_builds(project))


def _version(evr: str) -> str:
    return evr.split(":", 1)[-1].rsplit("-", 1)[0]


def recordable(binary: Binary, provides: list[str]) -> list[str]:
    """Return the `provides` rpm generated for `binary` to record: but those its spec declares, like its own name, and
    with its EVR, or its version, as %{evr}, or %{version}, so that they only change when what it generates does. An
    epoch 0 is the same as none, which rpm leaves out of what it generates.
    """
    evr = binary.evr.removeprefix("0:")
    declared = {p.replace(" = 0:", " = ") for p in binary.provides}
    placeholders = ((evr, "%{evr}"), (_version(evr), "%{version}"))
    return [
        next((p.removesuffix(v) + macro for v, macro in placeholders if p.endswith(f" = {v}")), p)
        for p in provides
        if p.replace(" = 0:", " = ") not in declared
    ]


def locked_packages(parsed: dict[str, Package], builds: Builds, arch: str) -> dict[str, Package]:
    """Return the `parsed` packages of `arch`, with what their builds found in `builds`: the requirements and
    capabilities rpm generated for their binary packages, with their versions, and their dynamic BuildRequires.
    """
    requires, provides, buildrequires = (getattr(builds, f).of(arch) for f in ("requires", "provides", "buildrequires"))
    packages = {name: package.model_copy(deep=True) for name, package in parsed.items()}
    for name, package in packages.items():
        package.buildrequires.extend(buildrequires.get(name, []))
        for b in package.binaries:
            b.requires.extend(requires.get(b.name, []))
            b.provides.extend(
                p.replace("%{evr}", b.evr).replace("%{version}", _version(b.evr)) for p in provides.get(b.name, [])
            )
    return packages
